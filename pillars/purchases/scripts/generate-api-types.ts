/**
 * Generates `src/contract/api-types.generated.ts` from the committed
 * OpenAPI spec. Output is a TS module exporting `paths` and `components`
 * types — zero runtime — that consumers compose with `openapi-fetch` to get
 * fully-typed HTTP calls without importing anything server-internal from
 * this pillar.
 *
 * Regenerate after an OpenAPI spec change:
 *   pnpm --filter @pops/purchases generate:api-types
 *
 * The `api-types-drift` job in `.github/workflows/quality.yml` re-runs this
 * for every pillar and fails the build on any diff — see
 * scripts/ci/check-api-types-drift.mjs.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const HERE = dirname(fileURLToPath(import.meta.url));
const OPENAPI_PATH = resolve(HERE, '..', 'openapi', 'purchases.openapi.json');
const OUTPUT_PATH = resolve(HERE, '..', 'src', 'contract', 'api-types.generated.ts');

async function main(): Promise<void> {
  const ast = await openapiTS(new URL(`file://${OPENAPI_PATH}`));
  const body = astToString(ast);
  const header = [
    '/**',
    ' * AUTOGENERATED by scripts/generate-api-types.ts via openapi-typescript.',
    ' * Do not edit by hand — regenerate via `pnpm -F @pops/purchases generate:api-types`.',
    ' */',
    '',
  ].join('\n');
  writeFileSync(OUTPUT_PATH, `${header}${body}`);

  execFileSync('pnpm', ['exec', 'oxfmt', '--write', OUTPUT_PATH], {
    cwd: resolve(HERE, '..'),
    stdio: 'inherit',
  });

  process.stdout.write(`[purchases] wrote ${OUTPUT_PATH}\n`);
}

main().catch((err: unknown) => {
  process.stderr.write(`[purchases] generate-api-types failed: ${String(err)}\n`);
  process.exit(1);
});
