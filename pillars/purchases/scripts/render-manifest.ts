import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MANIFEST_HEADER = '// AUTOGENERATED by scripts/generate-manifest.ts. Do not edit.';

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_JSON_PATH = resolve(HERE, '..', 'package.json');

export function readContractVersion(): string {
  const pkg: unknown = JSON.parse(readFileSync(PACKAGE_JSON_PATH, 'utf8'));
  if (
    typeof pkg !== 'object' ||
    pkg === null ||
    !('version' in pkg) ||
    typeof (pkg as { version: unknown }).version !== 'string'
  ) {
    throw new Error('package.json must declare a string `version` field');
  }
  return (pkg as { version: string }).version;
}

export function renderManifest(version: string): string {
  return `${MANIFEST_HEADER}
// Regenerated by \`pnpm -F @pops/purchases generate:manifest\`.
// Source version pinned at generation time: ${version}
import type {
  Purchase,
  PurchaseCharge,
  PurchaseChargeLink,
  PurchaseDocument,
  PurchaseItem,
  PurchaseItemAllocation,
  PurchaseItemUnit,
  PurchaseShipment,
} from './types/purchase.js';
import type { PurchaseSource } from './types/purchase-source.js';
import type { PurchasesError } from './errors.js';

export interface PurchasesContract {
  readonly pillar: 'purchases';
  readonly version: string;
  readonly entities: {
    readonly purchase: Purchase;
    readonly purchaseCharge: PurchaseCharge;
    readonly purchaseChargeLink: PurchaseChargeLink;
    readonly purchaseDocument: PurchaseDocument;
    readonly purchaseItem: PurchaseItem;
    readonly purchaseItemAllocation: PurchaseItemAllocation;
    readonly purchaseItemUnit: PurchaseItemUnit;
    readonly purchaseShipment: PurchaseShipment;
    readonly purchaseSource: PurchaseSource;
  };
  readonly errors: PurchasesError;
}
`;
}

export const MANIFEST_OUTPUT_PATH = resolve(HERE, '..', 'src', 'contract', 'manifest.generated.ts');

// Keep codegen output stable in the EX-2 sandbox, where the repo-root formatter config is absent.
export const MANIFEST_FORMAT_CONFIG_PATH = resolve(HERE, 'oxfmt-manifest.json');

/** Render with the package-carried config, independent of the checkout's root config. */
export function renderFormattedManifest(version: string): string {
  const dir = mkdtempSync(join(tmpdir(), 'manifest-render-'));
  try {
    const path = join(dir, 'manifest.generated.ts');
    writeFileSync(path, renderManifest(version));
    execFileSync(
      'pnpm',
      ['exec', 'oxfmt', '--config', MANIFEST_FORMAT_CONFIG_PATH, '--write', path],
      { stdio: 'ignore' }
    );
    return readFileSync(path, 'utf8');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
