import { createHash, randomUUID } from 'node:crypto';
import { constants } from 'node:fs';
import { copyFile, mkdir, mkdtemp, readdir, rm, link } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import Database from 'better-sqlite3';
import { drizzle } from 'drizzle-orm/better-sqlite3';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';

import { copyHistory, history, unchanged } from './migration-history.js';
import { runBfmMigrationKit, type BfmKitCompletion } from './migration-kit.js';
import { verifyBfmSnapshot, type SnapshotVerificationOptions } from './migration-snapshot.js';

export {
  BFM_MIGRATION_KIT_TIMEOUT_MS,
  runBfmMigrationKit,
  type BfmKitCompletion,
} from './migration-kit.js';

const repositoryRoot = fileURLToPath(new URL('../../../', import.meta.url));
const ownerRoot = fileURLToPath(new URL('../', import.meta.url));
const hash = (data: Uint8Array): string => createHash('sha256').update(data).digest('hex');

/** Tool seams; every database opened by the default path is a newly created private fixture. */
export interface SnapshotAdoptionOptions {
  repoRoot?: string;
  pillarRoot?: string;
  runKit?: (args: string[]) => BfmKitCompletion;
  fixtureReady?: (database: Database.Database) => void;
}

/** Provenance of the raw generated bytes and the unchanged private historical fixture. */
export interface SnapshotAdoptionResult {
  snapshot: string;
  snapshotSha256: string;
  historicalFiles: number;
  fixtureSha256: string;
  ledgerEntries: number;
}

async function adoptFixtureSnapshot(
  db: Database.Database,
  temporary: string,
  verification: SnapshotVerificationOptions
): Promise<SnapshotAdoptionResult> {
  const before = verification.history;
  const migrations = join(verification.pillarRoot, 'migrations');
  const ledger = db.prepare('SELECT * FROM __drizzle_migrations ORDER BY id').all();
  const dataBefore = db.serialize();
  const snapshot = await verifyBfmSnapshot(verification);
  if (
    JSON.stringify(db.prepare('SELECT * FROM __drizzle_migrations ORDER BY id').all()) !==
      JSON.stringify(ledger) ||
    !db.serialize().equals(dataBefore)
  )
    throw new Error('Introspection mutated the private fixture.');
  await unchanged(migrations, before.files);
  await copyFile(snapshot.sourcePath, temporary, constants.COPYFILE_EXCL);
  await link(temporary, join(migrations, 'meta', snapshot.name));
  return {
    snapshot: snapshot.name,
    snapshotSha256: hash(snapshot.bytes),
    historicalFiles: before.files.size,
    fixtureSha256: hash(dataBefore),
    ledgerEntries: ledger.length,
  };
}

/**
 * Adopt raw normal Kit-generated metadata for the last existing migration.
 * All database work uses an exclusively created private fixture; no live path,
 * environment/config database URL, SQL rewrite or applied-ledger write is accepted.
 * The current owner schema must generate zero changes against the pulled snapshot.
 */
export async function adoptBfmSnapshot({
  repoRoot = repositoryRoot,
  pillarRoot = ownerRoot,
  runKit = (args) => runBfmMigrationKit(repoRoot, args),
  fixtureReady,
}: SnapshotAdoptionOptions = {}): Promise<SnapshotAdoptionResult> {
  const migrations = join(pillarRoot, 'migrations');
  const before = await history(migrations);
  const existing = (await readdir(join(migrations, 'meta'))).filter((name) =>
    name.endsWith('_snapshot.json')
  );
  if (existing.length > 0)
    throw new Error('Migration snapshots already exist; adoption must not overwrite them.');
  const scratchParent = join(repoRoot, 'tmp');
  await mkdir(scratchParent, { recursive: true });
  const scratch = await mkdtemp(join(scratchParent, 'bfm-snapshot-adoption-'));
  const temporary = join(migrations, 'meta', `.adoption-${randomUUID()}.tmp`);
  try {
    const fixtureMigrations = join(scratch, 'historical');
    await copyHistory(before.files, fixtureMigrations);
    const databasePath = join(scratch, 'fixture.sqlite');
    const db = new Database(databasePath);
    try {
      migrate(drizzle(db), { migrationsFolder: fixtureMigrations });
      fixtureReady?.(db);
      return await adoptFixtureSnapshot(db, temporary, {
        history: before,
        pillarRoot,
        scratch,
        databasePath,
        runKit,
      });
    } finally {
      db.close();
    }
  } finally {
    await rm(temporary, { force: true });
    await rm(scratch, { recursive: true, force: true });
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2)
    throw new Error('Snapshot adoption accepts no database path or CLI options.');
  await adoptBfmSnapshot();
}
