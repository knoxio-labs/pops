import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, expectTypeOf, it } from 'vitest';

import { readContractVersion, renderFormattedManifest } from '../../../scripts/render-manifest.js';

import type { ListsContract } from '../manifest.js';
import type { AgendaItem } from '../types/agenda-item.js';
import type { ListItem } from '../types/list-item.js';
import type { Project } from '../types/project.js';
import type { Tag } from '../types/tag.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(HERE, '..', '..', '..');
const GENERATED_PATH = resolve(PACKAGE_ROOT, 'src', 'contract', 'manifest.generated.ts');
const AUTOGENERATED_HEADER = '// AUTOGENERATED by scripts/generate-manifest.ts. Do not edit.';

describe('ListsContract manifest type generation', () => {
  it('exposes ListItem on entities.listItem with byte-equal shape', () => {
    expectTypeOf<ListsContract['entities']['listItem']>().toEqualTypeOf<ListItem>();
  });

  it('exposes Project on entities.project with byte-equal shape', () => {
    expectTypeOf<ListsContract['entities']['project']>().toEqualTypeOf<Project>();
  });

  it('exposes Tag on entities.tag with byte-equal shape', () => {
    expectTypeOf<ListsContract['entities']['tag']>().toEqualTypeOf<Tag>();
  });

  it('exposes AgendaItem on entities.agendaItem with byte-equal shape', () => {
    expectTypeOf<ListsContract['entities']['agendaItem']>().toEqualTypeOf<AgendaItem>();
  });

  it('pins pillar discriminant and exposes the errors slot', () => {
    expectTypeOf<ListsContract['pillar']>().toEqualTypeOf<'lists'>();
    expectTypeOf<ListsContract['version']>().toEqualTypeOf<string>();
    expectTypeOf<ListsContract>().toHaveProperty('errors');
  });

  it('keeps the internal server API out of the contract surface', () => {
    expectTypeOf<ListsContract>().not.toHaveProperty('router');
  });

  it('emits the AUTOGENERATED header so hand-edits fail loudly', () => {
    const contents = readFileSync(GENERATED_PATH, 'utf8');
    expect(contents).toContain(AUTOGENERATED_HEADER);
  });

  // Re-rendered in memory rather than by spawning `pnpm run generate:manifest`
  // (POPS-1566). That spawn was `pnpm` -> `tsx` -> `node` -> a second
  // `pnpm exec`, on vitest's default 5s budget: 1.5s on an idle machine and a
  // timeout at 11.3s under multi-agent load, so the verdict tracked how busy
  // the machine was rather than the code. It also rewrote a committed file
  // mid-run, so a failure left the tree dirty.
  //
  // The claim is unchanged and slightly stronger: what the generator would
  // write must equal what is committed — which also catches a stale committed
  // manifest, not only a non-deterministic generator. One `oxfmt` subprocess
  // survives because the committed bytes are its output; the timeout allows
  // for it starting cold under contention.
  it('regeneration is idempotent (no diff on a second run)', { timeout: 30_000 }, () => {
    expect(renderFormattedManifest(readContractVersion())).toBe(
      readFileSync(GENERATED_PATH, 'utf8')
    );
  });
});
