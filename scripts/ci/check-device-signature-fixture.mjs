#!/usr/bin/env node
/**
 * Device-signature encoding guard — the Node half.
 *
 * The iOS app signs a refresh request with a P-256 key held in the phone's
 * Secure Enclave, and the BFM verifies that signature with `node:crypto`. Two
 * encodings have to agree for that to work and neither side defaults to the
 * other's choice:
 *
 *   - the signature bytes: ASN.1 DER (what `SecKeyCreateSignature` emits and
 *     what `node:crypto` verifies by default) versus raw `r‖s`;
 *   - the public key bytes: SPKI DER (what the pairing request carries) versus
 *     the X9.63 uncompressed point the Secure Enclave actually hands over.
 *
 * A mismatch on either is indistinguishable, from both logs, from an expired
 * or wrong token: the request simply 401s. So the choice is pinned by a
 * committed fixture — a real key, a real message and a real signature produced
 * on the Swift side — and asserted from both languages. This script is the
 * Node assertion. The Swift one is `DeviceSignatureFixtureTests` in
 * `clients/ios/Packages/Auth`.
 *
 * The fixture exists twice, and this script owns both copies:
 *
 *   - `clients/ios/Contracts/device-signature-v1.json` — canonical, because
 *     the vector can only be produced by the Swift side that generates it;
 *   - `pillars/bfm/contracts/device-signature-v1.json` — vendored, because
 *     ADR-043 forbids any unit depending on a client, so the BFM's own tests
 *     read a copy inside the BFM's unit boundary and never reach into
 *     `clients/`.
 *
 * That is the same consumer-vendors-a-copy shape ADR-033 established for
 * OpenAPI snapshots, and it carries the same risk: two copies can drift. So
 * byte-equality lives HERE, alongside the crypto, rather than in
 * `check-vendored-contracts.mjs` — that guard pairs a vendored copy with a
 * producing PILLAR by filename convention, and this pair inverts the direction
 * (the client is the producer) and matches no convention it could discover.
 * One guard proving both things beats two each proving half.
 *
 * Reading files under `clients/` from a repo-root script is not a dependency
 * on the client in the ADR-043 sense: nothing here imports it, links it or
 * ships it, and this guard exists precisely so the client and its pillar
 * cannot drift apart.
 *
 * The negative controls are the part that carries the weight. Asserting only
 * that the DER signature verifies would also pass if a future change made the
 * verifier accept anything, so the check also proves that the raw `r‖s`
 * encoding of the SAME signature is rejected by a DER verifier and accepted by
 * an `ieee-p1363` one. That is what makes "we chose DER" a fact a test can
 * fail on rather than a sentence in a comment.
 *
 * Usage:
 *   node scripts/ci/check-device-signature-fixture.mjs
 *   node scripts/ci/check-device-signature-fixture.mjs --self-test
 *
 * Exit 0 = the fixture verifies and every encoding assertion holds.
 */

import { createPublicKey, verify } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');

/**
 * Every copy of the fixture, canonical first. Repo-relative so the failure
 * messages, the self-test and the unit suite all name the same strings.
 *
 * Adding a copy is adding an entry here: the equality check is pairwise
 * against the canonical one, so a third consumer needs no new code.
 */
export const FIXTURE_COPIES = Object.freeze([
  Object.freeze({
    role: 'canonical (generated by clients/ios, reviewed once)',
    path: 'clients/ios/Contracts/device-signature-v1.json',
  }),
  Object.freeze({
    role: 'vendored (inside the BFM unit boundary, ADR-043)',
    path: 'pillars/bfm/contracts/device-signature-v1.json',
  }),
]);

/** The canonical copy — the one a drifted copy must be restored from. */
const CANONICAL = FIXTURE_COPIES[0];

/** The encoding contract, restated here so the fixture cannot redefine itself. */
const CONTRACT = Object.freeze({
  version: 1,
  curve: 'P-256',
  digest: 'SHA-256',
  publicKeyEncoding: 'spki-der',
  signatureEncoding: 'asn1-der',
  transportEncoding: 'base64',
});

/** OpenSSL's name for P-256, as `KeyObject.asymmetricKeyDetails` reports it. */
const OPENSSL_CURVE = 'prime256v1';

/** `node:crypto` digest name for {@link CONTRACT.digest}. */
const DIGEST = 'sha256';

/**
 * @typedef {object} Fixture
 * @property {number} version
 * @property {string} curve
 * @property {string} digest
 * @property {string} publicKeyEncoding
 * @property {string} signatureEncoding
 * @property {string} transportEncoding
 * @property {string} messageBase64
 * @property {string} publicKeySpkiDerBase64
 * @property {string} publicKeyX963Base64
 * @property {string} signatureDerBase64
 * @property {string} signatureRawBase64
 */

/**
 * Rebuild the X9.63 uncompressed point (`0x04 ‖ X ‖ Y`) from a public key, so
 * the SPKI the BFM stores can be compared against the bytes the Secure Enclave
 * exports. Going through JWK is the only route `node:crypto` offers to the
 * raw coordinates.
 *
 * @param {import('node:crypto').KeyObject} key
 * @returns {Buffer}
 */
function x963FromPublicKey(key) {
  const jwk = key.export({ format: 'jwk' });
  if (typeof jwk.x !== 'string' || typeof jwk.y !== 'string') {
    throw new Error('public key JWK carries no EC coordinates');
  }
  return Buffer.concat([
    Buffer.from([0x04]),
    Buffer.from(jwk.x, 'base64url'),
    Buffer.from(jwk.y, 'base64url'),
  ]);
}

/**
 * Run every assertion against a parsed fixture.
 *
 * Pure and dependency-free so the self-test can drive it with a deliberately
 * corrupted fixture and observe it fail.
 *
 * @param {Fixture} fixture
 * @returns {string[]} One message per failed assertion; empty means the fixture holds.
 */
export function checkFixture(fixture) {
  /** @type {string[]} */
  const failures = [];

  for (const [field, expected] of Object.entries(CONTRACT)) {
    const actual = fixture[/** @type {keyof typeof CONTRACT} */ (field)];
    if (actual !== expected) {
      failures.push(
        `${field}: fixture says ${JSON.stringify(actual)}, contract says ${JSON.stringify(expected)}`
      );
    }
  }

  const message = Buffer.from(fixture.messageBase64, 'base64');
  const spki = Buffer.from(fixture.publicKeySpkiDerBase64, 'base64');
  const derSignature = Buffer.from(fixture.signatureDerBase64, 'base64');
  const rawSignature = Buffer.from(fixture.signatureRawBase64, 'base64');

  /** @type {import('node:crypto').KeyObject | null} */
  let publicKey = null;
  try {
    publicKey = createPublicKey({ key: spki, format: 'der', type: 'spki' });
  } catch (error) {
    failures.push(`publicKeySpkiDerBase64 is not a parseable SPKI key: ${String(error)}`);
  }

  if (publicKey === null) return failures;

  if (publicKey.asymmetricKeyType !== 'ec') {
    failures.push(`public key is ${publicKey.asymmetricKeyType}, expected ec`);
  }
  const namedCurve = publicKey.asymmetricKeyDetails?.namedCurve;
  if (namedCurve !== OPENSSL_CURVE) {
    failures.push(`public key curve is ${namedCurve}, expected ${OPENSSL_CURVE}`);
  }

  const x963 = x963FromPublicKey(publicKey);
  if (!x963.equals(Buffer.from(fixture.publicKeyX963Base64, 'base64'))) {
    failures.push(
      'publicKeyX963Base64 is not the uncompressed point of publicKeySpkiDerBase64 — ' +
        'the SPKI wrapping the app performs does not round-trip'
    );
  }
  if (rawSignature.length !== 64) {
    failures.push(`signatureRawBase64 is ${rawSignature.length} bytes, expected 64 (r‖s on P-256)`);
  }

  if (!verify(DIGEST, message, { key: publicKey, dsaEncoding: 'der' }, derSignature)) {
    failures.push('the DER signature does not verify — the encoding contract is already broken');
  }

  // Negative controls. Each of these passing would mean the guard cannot tell
  // the two encodings apart, which is the entire failure it exists to catch.
  if (verify(DIGEST, message, { key: publicKey, dsaEncoding: 'der' }, rawSignature)) {
    failures.push(
      'a raw r‖s signature was accepted by a DER verifier — the encodings are not being distinguished'
    );
  }
  if (!verify(DIGEST, message, { key: publicKey, dsaEncoding: 'ieee-p1363' }, rawSignature)) {
    failures.push(
      'signatureRawBase64 is not the raw encoding of signatureDerBase64 — the negative control proves nothing'
    );
  }
  const tampered = Buffer.concat([message, Buffer.from('!')]);
  if (verify(DIGEST, tampered, { key: publicKey, dsaEncoding: 'der' }, derSignature)) {
    failures.push('a modified message verified against the committed signature');
  }

  return failures;
}

/**
 * Check every copy of the fixture: each one present, each one byte-identical
 * to the canonical copy, and each one passing {@link checkFixture} on its own.
 *
 * Verifying each copy separately rather than only the canonical one is not
 * redundant with the equality check — it is what makes the two independent.
 * Should the equality comparison ever be neutered, the crypto assertions still
 * run against the bytes the BFM's tests actually read.
 *
 * Pure in its I/O so the self-test can drive it with a reader that returns
 * drifted or missing copies.
 *
 * @param {(repoRelativePath: string) => string | null} read Reads a copy, or null if absent.
 * @returns {string[]} One message per failure; empty means every copy holds.
 */
export function checkAllCopies(read) {
  /** @type {string[]} */
  const failures = [];
  /** @type {Map<string, string>} */
  const texts = new Map();

  for (const { role, path } of FIXTURE_COPIES) {
    const text = read(path);
    if (text === null) {
      failures.push(`${path}: missing — the ${role} copy of the fixture is not on disk`);
      continue;
    }
    texts.set(path, text);
  }

  const canonicalText = texts.get(CANONICAL.path);
  if (canonicalText !== undefined) {
    for (const [path, text] of texts) {
      if (path !== CANONICAL.path && text !== canonicalText) {
        failures.push(
          `${path}: drifted from ${CANONICAL.path} — the copies must be byte-identical`
        );
      }
    }
  }

  for (const [path, text] of texts) {
    /** @type {Fixture} */
    let fixture;
    try {
      fixture = JSON.parse(text);
    } catch (error) {
      failures.push(`${path}: not parseable as JSON — ${String(error)}`);
      continue;
    }
    for (const failure of checkFixture(fixture)) failures.push(`${path}: ${failure}`);
  }

  return failures;
}

/**
 * Self-test: prove the assertions actually fail on a fixture that has been
 * broken in each of the ways this guard exists to catch. A guard nobody has
 * watched fail is a guard nobody knows works.
 *
 * @param {Fixture} valid A fixture already known to pass.
 * @returns {boolean}
 */
function selfTest(valid) {
  /** @type {[string, Fixture][]} */
  const corruptions = [
    [
      'signature swapped for its raw r‖s form',
      { ...valid, signatureDerBase64: valid.signatureRawBase64 },
    ],
    [
      'public key swapped for its X9.63 form',
      { ...valid, publicKeySpkiDerBase64: valid.publicKeyX963Base64 },
    ],
    ['message altered', { ...valid, messageBase64: Buffer.from('different').toString('base64') }],
    ['contract metadata drifted', { ...valid, signatureEncoding: 'ieee-p1363' }],
    [
      'raw signature no longer matches the DER one',
      { ...valid, signatureRawBase64: Buffer.alloc(64).toString('base64') },
    ],
  ];

  let ok = checkFixture(valid).length === 0;
  if (!ok) console.error('SELF-TEST FAILED: the committed fixture does not pass its own checks');

  for (const [label, corrupted] of corruptions) {
    const caught = checkFixture(corrupted).length > 0;
    if (!caught) {
      console.error(`SELF-TEST FAILED: not caught — ${label}`);
      ok = false;
    }
  }

  const validText = JSON.stringify(valid);
  /** @param {Map<string, string>} files */
  const readerOver = (files) => (/** @type {string} */ p) => files.get(p) ?? null;
  const identical = new Map(FIXTURE_COPIES.map(({ path }) => [path, validText]));

  /** @type {[string, string[]][]} */
  const copyCases = [
    ['every copy identical', checkAllCopies(readerOver(identical))],
    [
      'one copy edited without the other',
      checkAllCopies(
        readerOver(
          new Map(identical).set(
            FIXTURE_COPIES[1].path,
            JSON.stringify({ ...valid, version: valid.version + 1 })
          )
        )
      ),
    ],
    [
      'one copy reformatted but semantically equal',
      checkAllCopies(
        readerOver(new Map(identical).set(FIXTURE_COPIES[1].path, JSON.stringify(valid, null, 4)))
      ),
    ],
    ['a copy deleted', checkAllCopies(readerOver(new Map([[CANONICAL.path, validText]])))],
  ];

  const [[, identicalFailures], ...driftCases] = copyCases;
  if (identicalFailures.length > 0) {
    console.error('SELF-TEST FAILED: identical copies were reported as drifted');
    ok = false;
  }
  for (const [label, failures] of driftCases) {
    if (failures.length === 0) {
      console.error(`SELF-TEST FAILED: not caught — ${label}`);
      ok = false;
    }
  }

  if (ok) {
    console.log(
      `self-test OK — accepts the fixture, rejects ${corruptions.length} corruptions of it ` +
        `and ${driftCases.length} ways the ${FIXTURE_COPIES.length} copies can disagree.`
    );
  }
  return ok;
}

function main() {
  const argv = process.argv.slice(2);
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log('Usage: node scripts/ci/check-device-signature-fixture.mjs [--self-test]');
    process.exit(2);
  }

  /** @param {string} repoRelativePath @returns {string | null} */
  const read = (repoRelativePath) => {
    try {
      return readFileSync(join(repoRoot, repoRelativePath), 'utf8');
    } catch {
      return null;
    }
  };

  if (argv.includes('--self-test')) {
    // The self-test needs a fixture it can corrupt, and the canonical copy is
    // the only source of one. Both failure modes are reported rather than
    // thrown: this runs as the FIRST step of its CI job, so an unhandled
    // SyntaxError here would report a broken fixture as a broken guard.
    const canonical = read(CANONICAL.path);
    if (canonical === null) {
      console.error(`FAIL — cannot read ${CANONICAL.path}`);
      process.exit(1);
    }
    /** @type {Fixture} */
    let valid;
    try {
      valid = JSON.parse(canonical);
    } catch (error) {
      console.error(`FAIL — ${CANONICAL.path} is not parseable as JSON: ${String(error)}`);
      process.exit(1);
    }
    process.exit(selfTest(valid) ? 0 : 1);
  }

  const failures = checkAllCopies(read);
  if (failures.length === 0) {
    console.log(
      `OK — ${String(FIXTURE_COPIES.length)} identical copies of the device-signature fixture, ` +
        'each verifying under node:crypto, DER end to end.'
    );
    process.exit(0);
  }

  console.error(`FAIL — ${String(failures.length)} device-signature problem(s):`);
  for (const failure of failures) console.error(`  ${failure}`);
  console.error(
    '\nThe iOS app and the BFM must agree on ECDSA P-256 encodings, and every copy of ' +
      'the fixture must be byte-identical. Re-vendor with `mise run fixture:device-signature:vendor`. ' +
      'Regenerate the vector itself with `mise run fixture:device-signature` only if the ' +
      'contract changed, and update both sides’ assertions together.'
  );
  process.exit(1);
}

if (resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? '')) {
  main();
}
